"""The report outside the browser (§15 E): a summary shared with the UI, Markdown for people, SARIF for GitHub code scanning.
Everything here reads stored findings, which were masked before they were saved."""

from models import SEVERITIES

CONFIDENCE = ["Confirmed reachable", "Likely", "Needs review"]
# GitHub code scanning ranks alerts by this number (CVSS-like, 0-10)
SECURITY_SEVERITY = {"Critical": "9.5", "High": "8.0", "Medium": "5.5", "Low": "2.0"}
LEVEL = {"Critical": "error", "High": "error", "Medium": "warning", "Low": "note"}


def summary(findings):
    """{verdict, top}: one plain sentence for the whole report and the three findings that could hurt most."""
    live = sorted((f for f in findings if not f.is_false_positive),
                  key=lambda f: (SEVERITIES.index(f.severity), CONFIDENCE.index(f.confidence), not f.money_risk))
    count = {s: sum(f.severity == s for f in live) for s in SEVERITIES}

    def n(k, word):
        return f"{k} {word}{'s' * (k != 1)}"

    if count["Critical"]:
        verdict = f"Attackers could do real damage today. Fix the {n(count['Critical'], 'critical issue')} first."
    elif count["High"]:
        verdict = f"No critical holes, but {n(count['High'], 'high-risk issue')} should be fixed before you launch."
    elif count["Medium"]:
        verdict = f"No serious holes. {n(count['Medium'], 'medium issue')} worth fixing when you can."
    elif count["Low"]:
        verdict = "Only minor hygiene items. Nothing an attacker can use right away."
    else:
        verdict = "No issues found in what we checked."
    return {"verdict": verdict, "top": [f.id for f in live[:3]]}


def markdown(scan, grade, findings):
    live = [f for f in findings if not f.is_false_positive]
    noise = [f for f in findings if f.is_false_positive]
    s = summary(findings)
    top = [f for f in live if f.id in s["top"]]
    out = [f"# VibeGuard report: {scan['source_label'] or scan['source_type']}", "",
           f"**Grade {grade}** · risk score {scan['risk_score']}/100 · scanned {scan['created_at']}", "", s["verdict"], ""]
    out += ["| " + " | ".join(SEVERITIES) + " |", "|" + "---|" * len(SEVERITIES),
            "| " + " | ".join(str(sum(f.severity == sev for f in live)) for sev in SEVERITIES) + " |", ""]
    if top:
        out += ["## This could hurt you", ""] + [f"{i}. **{f.title}** ({f.severity}). {f.impact}" for i, f in enumerate(top, 1)] + [""]
    passed = [p for st in scan["steps"] for p in st.get("passed") or []]
    if passed:
        out += ["## Already right", ""] + [f"- {p}" for p in passed] + [""]
    out += ["## Findings", ""] + [line for f in live for line in _finding_md(f)]
    if noise:
        out += ["## Filtered out as not a real risk", ""] + [f"- {f.title} ({_where(f)}): {f.ai_note or f.triage_note}" for f in noise] + [""]
    checked = [f"- {st['label']}: {st.get('note', '')}" + (f" in {st['checked']}" if st.get("checked") else "")
               for st in scan["steps"] if st["state"] == "done"]
    skipped = [f"- {st['label']}: {st.get('note', '')}" for st in scan["steps"] if st["state"] in ("skipped", "failed")]
    out += ["## What was checked", ""] + checked + ([""] + ["Not checked:"] + skipped if skipped else []) + [""]
    out += ["---", "Generated by VibeGuard. Fixes are suggestions: review them before you apply them. Secrets in this report are masked."]
    return "\n".join(out) + "\n"


def _where(f):
    return f"{f.file}:{f.line}" if f.line else f.file or f.package


def _finding_md(f):
    out = [f"### {f.severity}: {f.title}", "", f"`{_where(f)}` · {f.confidence}" + (" · $ risk" if f.money_risk else ""), ""]
    if f.impact:
        out += [f"**Impact:** {f.impact}", ""]
    if f.severity_reason:
        out += [f"**Why {f.severity.lower()}:** {f.severity_reason}", ""]
    if f.ai_note:
        out += [f"**AI review:** {f.ai_note}", ""]
    if f.explanation:
        out += [f.explanation, ""]
    if f.code_snippet:
        out += ["```", f.code_snippet, "```", ""]
    if f.evidence:
        out += [f"- {e}" for e in f.evidence] + [""]
    if f.fix_diff:
        out += ["**Suggested fix:**", "", "```diff", f.fix_diff, "```", ""]
    if f.reprompt:
        out += ["**Ask your AI builder:**", "", "> " + f.reprompt.replace("\n", "\n> "), ""]
    if f.refs:
        out += ["References: " + ", ".join(f.refs), ""]
    return out


def sarif(findings):
    """SARIF 2.1.0, the format GitHub code scanning uploads. Filtered findings are included as suppressed, with the reason."""
    rules, results = {}, []
    for f in findings:
        rule = f.raw_rule_id or f.title
        rules.setdefault(rule, {
            "id": rule, "name": f.title, "shortDescription": {"text": f.title},
            "fullDescription": {"text": f.impact or f.title}, **({"helpUri": f.refs[0]} if f.refs else {}),
            "help": {"text": f.reprompt or f.explanation or f.title},
            "properties": {"security-severity": SECURITY_SEVERITY[f.severity], "tags": ["security", *f.cwe]},
        })
        result = {
            "ruleId": rule, "level": LEVEL[f.severity],
            "message": {"text": " ".join(x for x in (f.title + ".", f.impact) if x)},
            "properties": {"severity": f.severity, "confidence": f.confidence, "kind": f.kind,
                           **({"package": f.package} if f.package else {}), **({"ai_review": f.ai_note} if f.ai_note else {})},
        }
        if f.file:
            region = {"startLine": f.line, "endLine": max(f.end_line, f.line)} if f.line else {}
            result["locations"] = [{"physicalLocation": {"artifactLocation": {"uri": f.file}, **({"region": region} if region else {})}}]
        if f.fix_diff:
            result["properties"]["suggested_fix"] = f.fix_diff
        if f.is_false_positive:
            result["suppressions"] = [{"kind": "external", "justification": f.ai_note or f.triage_note or "Filtered as not a real risk"}]
        results.append(result)
    return {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
        "runs": [{"tool": {"driver": {"name": "VibeGuard", "rules": list(rules.values())}},
                  "results": results}],
    }
